def main():
    rows = []
    for rq in sorted(S, key=lambda k: int(k[3:])):
        items = S[rq]
        assert len(items) == 9, rq
        for c, it in zip(CRIT, items):
            sc, reason = it.split("|", 1)
            sc = int(sc)
            assert 1 <= sc <= 5
            rows.append({"rq_id": rq, "criterion": c, "score": sc, "reason": reason})
    assert len(rows) == 540, len(rows)
    with open(os.path.join(ROOT, "outputs/evaluation/scores_coordinator.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["rq_id", "criterion", "score", "reason"])
        w.writeheader()
        w.writerows(rows)
    tot = {}
    for r in rows:
        tot[r["rq_id"]] = tot.get(r["rq_id"], 0) + r["score"]
    for rq, t in sorted(tot.items(), key=lambda x: -x[1])[:15]:
        print(rq, t)


if __name__ == "__main__":
    main()
