def main():
    rows = []
    for cid in sorted(S, key=lambda k: int(k[2:])):
        assert len(S[cid]) == 11, cid
        for c, it in zip(CRIT, S[cid]):
            sc, r = it.split("|", 1)
            rows.append({"cand_id": cid, "criterion": c, "score": int(sc), "reason": r})
    assert len(rows) == 308
    with open(os.path.join(ROOT, "outputs/revision/scores_coordinator.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["cand_id", "criterion", "score", "reason"])
        w.writeheader()
        w.writerows(rows)
    tot, new2 = {}, {}
    for r in rows:
        tot[r["cand_id"]] = tot.get(r["cand_id"], 0) + r["score"]
        if r["criterion"] in CRIT[-2:]:
            new2[r["cand_id"]] = new2.get(r["cand_id"], 0) + r["score"]
    for cid, t in sorted(tot.items(), key=lambda x: (-x[1], -new2[x[0]]))[:12]:
        print(cid, t, new2[cid])


if __name__ == "__main__":
    main()
